const cart = ['arroz', 'feijão', 'macarrão', 'carne', 'frango'];

// Adicionando um item no final do array
cart.push('batata');
console.log(cart); // ['arroz', 'feijão', 'macarrão', 'carne', 'frango', 'batata']
 const removedItem = cart.pop(); // Removendo o último item do array
console.log(removedItem); // 'batata'
